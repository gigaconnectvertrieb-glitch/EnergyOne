-- Stufe 13: Agentur-Sätze. Wo die PDF-Liste noch fehlt, aus Stufe 1 / 0,54 ableiten (86/160).
insert into tariff_bands (id, tariff_id, stufe, kwh_from, kwh_to, amount_eur, amount_ct_kwh)
select
  left(id, 40) || '-s13',
  tariff_id,
  13,
  kwh_from,
  kwh_to,
  round(amount_eur / 0.54, 2),
  amount_ct_kwh / 0.54
from tariff_bands b
where stufe = 1
  and not exists (
    select 1 from tariff_bands x
    where x.tariff_id = b.tariff_id and x.stufe = 13
      and x.kwh_from = b.kwh_from and x.kwh_to = b.kwh_to
  );

