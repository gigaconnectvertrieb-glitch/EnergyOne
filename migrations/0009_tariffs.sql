  id text primary key,
  tariff_id text not null references tariffs(id) on delete cascade,
  stufe integer not null,
  kwh_from integer not null,
  kwh_to integer not null,
  amount_eur numeric(10,2) not null default 0,
  amount_ct_kwh numeric(14,8) not null default 0
);
